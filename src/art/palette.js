const WHITE = "#fff4d6";
const BLACK = "#0a1013";
const OUTLINE = "#071014";

function buildPalette(family, seed) {
  const [h, s, l, accentHue, accentSat, accentLight] = family;
  const hueShift = (seed % 9) - 4;
  const satShift = ((seed >>> 4) % 9) - 4;
  const lightShift = ((seed >>> 8) % 7) - 3;
  const hue = h + hueShift;
  const sat = Math.max(10, Math.min(92, s + satShift));
  const light = Math.max(22, Math.min(82, l + lightShift));
  const accentH = accentHue + ((seed >>> 12) % 7) - 3;
  return {
    base: hslToHex(hue, sat, light),
    light: hslToHex(hue, Math.min(94, sat + 5), Math.min(88, light + 14)),
    dark: hslToHex(hue, Math.max(8, sat - 4), Math.max(12, light - 18)),
    hi: hslToHex(hue, Math.min(96, sat + 10), Math.min(94, light + 25)),
    accent: hslToHex(accentH, accentSat, accentLight),
    accentLight: hslToHex(accentH, Math.min(94, accentSat + 6), Math.min(90, accentLight + 13)),
    shadow: hslToHex(hue, Math.max(8, sat - 8), Math.max(10, light - 28)),
    outline: OUTLINE,
    white: WHITE,
    black: BLACK,
  };
}

export function resolvePalette(element) {
  const key = element.palette || element.category;
  const familyName = ALIASES[key] || keywordFamily(key) || CATEGORY_FAMILY[element.category] || "parchment";
  const family = FAMILIES[familyName] || FAMILIES.parchment;
  const seed = hashString(`${element.id}|${key}|${element.shape}`);
  return buildPalette(family, seed);
}

