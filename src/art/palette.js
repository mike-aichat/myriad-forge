function keywordFamily(key) {
  const value = String(key || "").toLowerCase();
  if (!value) return null;
  if (/magic|rune|spell|arcane|portal|mystic|wizard|sorcer|elixir|alchemy|philos|soul|spirit|dream|ghost|angel/.test(value)) return "magic";
  if (/tech|circuit|chip|robot|laser|rocket|satellite|radar|sonar|quantum|algorithm|computer|digital|network|signal/.test(value)) return "tech";
  if (/star|cosmos|galaxy|nebula|cosmic|universe|space|planet|moon|night|void|dark/.test(value)) return "cosmos";
  if (/fire|flame|lava|volcano|ember|forge|furnace|meteor|sun|candle|phoenix/.test(value)) return "fire";
  if (/water|sea|lake|river|rain|wave|tide|spring|waterfall|foam|ocean/.test(value)) return "water";
  if (/ice|snow|frost|glacier|crystal|glass/.test(value)) return "ice";
  if (/iron|steel|metal|copper|bronze|silver|gold|magnet|rust|brass/.test(value)) return "steel";
  if (/stone|rock|mountain|cave|ore|cliff|island/.test(value)) return "stone";
  if (/plant|leaf|grass|moss|forest|tree|herb|tea|seed|flower|fruit|kelp|vine/.test(value)) return "plant";
  if (/fish|shark|whale|octopus|crab|shell|turtle|frog|lizard|snake|bird|owl|bug|bee|spider|worm|beast|wolf|fox|cat|horse|bear|deer|bird|bat|panda|lion|tiger|rabbit/.test(value)) return "fur";
  if (/human|skin|flesh|blood|bone/.test(value)) return "human";
  if (/paper|book|scroll|map|news/.test(value)) return "paper";
  if (/cloth|leather|silk|wool|fiber|wall/.test(value)) return "cloth";
  if (/love|heart|emotion|courage|war|blood/.test(value)) return "heart";
  if (/peace|hope|light|halo/.test(value)) return "peace";
  return null;
}

